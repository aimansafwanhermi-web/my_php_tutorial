//Loop ialah satu cara untuk mengulang sesuatu kod berulang kali sehingga syarat tertentu dipenuhi. Terdapat beberapa
jenis loop dalam PHP iaitu for loop, while loop, do while loop dan foreach loop. For loop digunakan apabila kita tahu
berapa kali kita ingin mengulang sesuatu kod. While loop digunakan apabila kita ingin mengulang sesuatu kod selagi
syarat tertentu dipenuhi. Do while loop hampir sama dengan while loop tetapi kod akan dijalankan sekurang-kurangnya
sekali sebelum syarat diperiksa. Foreach loop digunakan untuk mengulang setiap elemen dalam array.
